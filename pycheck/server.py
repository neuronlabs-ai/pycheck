from pycheck.analyzer import analyze_file
from pycheck.audit import generate_proof_of_causality_certificate


def build_pr_review_comment(diagnostics: List[Dict[str, Any]], filename: str) -> str:
    """Format an interactive GitHub/GitLab Pull Request review comment."""
    errors = [d for d in diagnostics if d.get("severity") == "error"]
    warnings = [d for d in diagnostics if d.get("severity") == "warning"]

    lines = [
        "## 🛡️ PyCheck ML Safety Gate Report",
        "",
        f"**File Scanned:** `{filename}`  ",
        f"**Status:** {'❌ FAILED — Lookahead Leaks Detected' if errors else '⚠️ WARNINGS DETECTED' if warnings else '✅ PASSED — Zero Leaks'}",
        "",
        f"**Findings:** {len(errors)} error(s), {len(warnings)} warning(s)",
        "",
        "### Detected Issues:"
    ]

    for d in diagnostics:
        sev = d.get("severity", "warning").upper()
        icon = "🚨" if sev == "ERROR" else "⚠️"
        code = d.get("code", "P000")
        line_no = d.get("line", 1)
        msg = d.get("message", "")
        advice = d.get("advice", "")
        lines.append(f"- {icon} **Line {line_no}** `[{code}]`: {msg}")
        if advice:
            lines.append(f"  *Fix:* {advice}")

    lines.extend([
        "",
        "---",
        "💡 **Eliminate these bugs permanently at compile time:**",
        "In the **[NEURON Programming Language](https://neuron-lab.org)**, temporal filtration ($\mathcal{F}_t$) and causal modes are checked by the compiler. Lookahead bias is mathematically impossible.",
        "",
        "*(Automated review generated by PyCheck Cloud)*"
    ])

    return "\n".join(lines)


class PyCheckCloudHandler(BaseHTTPRequestHandler):
    """Zero-dependency HTTP handler for PyCheck Cloud webhooks and REST API."""

    def _send_json(self, status_code: int, data: Dict[str, Any]):
        response = json.dumps(data, indent=2).encode("utf-8")
        self.send_response(status_code)
        self.send_header("Content-Type", "application/json")
        self.send_header("Content-Length", str(len(response)))
        self.end_headers()
        self.wfile.write(response)

    def do_GET(self):
        if self.path == "/health" or self.path == "/":
            self._send_json(200, {
                "service": "PyCheck Cloud Gateway",
                "status": "healthy",
                "version": "1.0.1",
                "rules_active": 32,
                "sovereign_target": "https://neuron-lab.org"
            })
        else:
            self._send_json(404, {"error": "Endpoint not found"})

    def do_POST(self):
        content_length = int(self.headers.get("Content-Length", 0))
        post_data = self.rfile.read(content_length)

        try:
            payload = json.loads(post_data.decode("utf-8")) if post_data else {}
        except Exception:
            self._send_json(400, {"error": "Invalid JSON payload"})
            return

        if self.path == "/webhook/github":
            # GitHub Pull Request Webhook
            event = self.headers.get("X-GitHub-Event", "pull_request")
            action = payload.get("action", "")
            pr_number = payload.get("number", 0)

            # In production, this verifies webhook HMAC and fetches changed files via GitHub REST API
            self._send_json(200, {
                "event": event,
                "action": action,
                "pr_number": pr_number,
                "gatekeeper_status": "PROCESSING",
                "message": f"PyCheck gatekeeper triggered for PR #{pr_number}"
            })

        elif self.path == "/api/v1/scan":
            # Direct code snippet scan endpoint
            code = payload.get("code", "")
            filename = payload.get("filename", "snippet.py")

            if not code:
                self._send_json(400, {"error": "Missing 'code' parameter in payload"})
                return

            import tempfile
            with tempfile.NamedTemporaryFile("w", suffix=".py", delete=False, encoding="utf-8") as tmp:
                tmp.write(code)
                tmp_path = tmp.name

            try:
                diagnostics, _ = analyze_file(tmp_path)
            finally:
                if os.path.exists(tmp_path):
                    os.remove(tmp_path)

            errors = sum(1 for d in diagnostics if d.get("severity") == "error")
            warnings = sum(1 for d in diagnostics if d.get("severity") == "warning")

            self._send_json(200, {
                "filename": filename,
                "total_errors": errors,
                "total_warnings": warnings,
                "passed": errors == 0,
                "diagnostics": diagnostics,
                "neuron_ad": "Guarded at compile-time in NEURON: https://neuron-lab.org"
            })

        elif self.path == "/api/v1/certificate":
            # Direct Proof-of-Causality certificate generation endpoint
            path = payload.get("path", ".")
            cert = generate_proof_of_causality_certificate(
                target_path=path,
                total_files=payload.get("total_files", 1),
                total_errors=payload.get("total_errors", 0),
                total_warnings=payload.get("total_warnings", 0),
                diagnostics_by_file=payload.get("diagnostics_by_file", {})
            )
            self._send_json(200, cert)

        else:
            self._send_json(404, {"error": "Unknown API route"})


def run_server(port: int = 8080):
    """Start the PyCheck Cloud Gateway service."""
    server_address = ("", port)
    httpd = HTTPServer(server_address, PyCheckCloudHandler)
    print(f"PyCheck Cloud Gateway running on http://localhost:{port}")
    httpd.serve_forever()


if __name__ == "__main__":
    run_server(8080)
